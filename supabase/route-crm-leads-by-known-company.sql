as $$
declare
  v_known public.crm_known_company_leads%rowtype;
  v_payload text;
begin
  select * into v_known
  from public.crm_known_company_leads
  where subscriber_id = new.subscriber_id
  limit 1;

  if found then
    new.company_key := v_known.company_key;

    if new.whatsapp_phone is null then
      new.whatsapp_phone := v_known.whatsapp_phone;
